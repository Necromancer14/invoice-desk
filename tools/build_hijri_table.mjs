#!/usr/bin/env node
// Writes src/invoice_desk/hijri_table.py: the first Gregorian day of every Umm al-Qura month from 1420 to 1500 AH.
//
//   node tools/build_hijri_table.mjs
//
// The calendar comes from the ICU data built into Node (the "islamic-umalqura" calendar), so nothing is downloaded.
// Re-run it only to widen the range; the output is checked in.
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const FIRST = 1420, LAST = 1500;
const fmt = new Intl.DateTimeFormat("en-u-ca-islamic-umalqura-nu-latn", { year: "numeric", month: "numeric", day: "numeric", timeZone: "UTC" });
const DAY = 86400000;
const starts = new Map(); // "y-m" -> days since 1970-01-01
for (let t = Date.UTC(1999, 0, 1); t <= Date.UTC(2078, 11, 31); t += DAY) {
  const p = Object.fromEntries(fmt.formatToParts(new Date(t)).map((x) => [x.type, x.value]));
  const y = Number(p.year), m = Number(p.month), d = Number(p.day);
  if (d === 1 && y >= FIRST && y <= LAST + 1) starts.set(`${y}-${m}`, t / DAY);
}
const out = [];
for (let y = FIRST; y <= LAST; y++) for (let m = 1; m <= 12; m++) {
  const v = starts.get(`${y}-${m}`);
  if (v === undefined) throw new Error(`no start found for ${y}-${m}`);
  out.push(v);
}
out.push(starts.get(`${LAST + 1}-1`)); // end of the last month
const rows = [];
for (let i = 0; i < out.length; i += 12) rows.push("    " + out.slice(i, i + 12).join(", ") + ",");
const py = `"""Umm al-Qura calendar months, generated by tools/build_hijri_table.mjs from the ICU data in Node. Do not edit by hand.

MONTH_STARTS[(year - FIRST_YEAR) * 12 + (month - 1)] is the first day of that Hijri month, as days since 1970-01-01.
The last entry is the day after the end of ${LAST} AH.
"""
FIRST_YEAR = ${FIRST}
LAST_YEAR = ${LAST}
SOURCE = "ICU ${process.versions.icu} islamic-umalqura"
MONTH_STARTS = (
${rows.join("\n")}
)
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "invoice_desk", "hijri_table.py");
writeFileSync(target, py);
console.log(`wrote ${out.length - 1} months (${FIRST} to ${LAST} AH) to ${target}`);
